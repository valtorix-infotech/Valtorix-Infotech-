"""Download the web fonts and write a local @font-face stylesheet.

    python scripts/build_fonts.py

Why this exists: the fonts were loaded from Google Fonts, which means a
third-party render-blocking stylesheet and a font swap whose layout impact
depends on what fallback the visitor's device happens to have. On a machine
with no matching font the swap reflowed the page badly enough to score
0.255 CLS.

Self-hosting them with `font-display: optional` removes the swap entirely:
the real font is used when it arrives in time, the fallback is used when it
does not, and the page never moves either way.

    python scripts/build_fonts.py
"""
import io
import os
import re
import urllib.parse
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
FONTS = os.path.join(ROOT, 'fonts')
OUT = os.path.join(FONTS, 'fonts.css')

# The families and weights the stylesheet actually uses. Anything else is
# dead weight in the repository and in the visitor's download.
FAMILIES = [
    ('Manrope', 'Manrope', [400, 500, 600, 700]),
    ('Oxanium', 'Oxanium', [600, 700]),
    ('Sora', 'Sora', [600, 700]),
]

# a modern browser gets woff2
UA = ('Mozilla/5.0 (Windows NT 10.0; Win64; x64) AppleWebKit/537.36 '
      '(KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36')

# The site is English. Only the latin and latin-ext subsets are needed -
# latin-ext is the one that carries the rupee sign (U+20B9). The cyrillic,
# greek and vietnamese subsets are never fetched, so they are not kept.
KEEP_SUBSETS = {'latin', 'latin-ext'}

GOOGLE = 'https://fonts.googleapis.com/css2?family=%s&display=optional'


def google_css(family, weights):
    """The CSS for one family.

    Each family is asked for on its own - a combined request for all three
    comes back short.
    """
    spec = '%s:wght@%s' % (family, ';'.join(str(w) for w in weights))
    url = GOOGLE % urllib.parse.quote(spec, safe=':@;')
    return fetch(url).decode('utf-8')


def fetch(url):
    req = urllib.request.Request(url, headers={'User-Agent': UA})
    with urllib.request.urlopen(req, timeout=60) as r:
        return r.read()


def main():
    os.makedirs(FONTS, exist_ok=True)

    out = ["""/* ==========================================================================
   The web fonts, served from this site.
   --------------------------------------------------------------------------
   Generated by scripts/build_fonts.py - do not edit by hand.

   `font-display: optional` is the point of hosting these here: the browser
   uses the real font if it arrives in time and the fallback if it does not,
   and it never swaps one for the other after the first paint. A swap is
   what makes a page jump when the font changes the line wrapping, and the
   fallback a visitor's device happens to have decides how much it jumps.
   ========================================================================== */

"""]

    downloaded = 0
    total = 0
    kept = []
    for family, _, weights in FAMILIES:
        css = google_css(family, weights)
        blocks = re.findall(r'/\*\s*([\w-]+)\s*\*/\s*@font-face\s*\{(.*?)\}', css, re.S)
        print('  %-10s %d face(s)' % (family, len(blocks)))
        for subset, body in blocks:
            if subset not in KEEP_SUBSETS:
                continue
            url = re.search(r'url\((https://[^)]+\.woff2)\)', body)
            if not url:
                continue
            weight = re.search(r'font-weight:\s*(\d+)', body)
            style = re.search(r'font-style:\s*(\w+)', body)
            fam = re.search(r"font-family:\s*'([^']+)'", body)
            unicode_range = re.search(r'unicode-range:\s*([^;]+);', body)
            if not (weight and fam):
                continue

            name = '%s-%s-%s.woff2' % (fam.group(1).lower(),
                                        weight.group(1),
                                        subset.lower())
            path = os.path.join(FONTS, name)
            kept.append(name)
            if not os.path.exists(path):
                data = fetch(url.group(1))
                with open(path, 'wb') as fh:
                    fh.write(data)
                downloaded += 1
            size = os.path.getsize(path)
            total += size

            out.append('@font-face {\n')
            out.append('  font-family: "%s";\n' % fam.group(1))
            out.append('  font-style: %s;\n' % (style.group(1) if style else 'normal'))
            out.append('  font-weight: %s;\n' % weight.group(1))
            out.append('  font-display: optional;\n')
            out.append('  src: url("%s") format("woff2");\n' % name)
            if unicode_range:
                out.append('  unicode-range: %s;\n' % unicode_range.group(1).strip())
            out.append('}\n\n')

    io.open(OUT, 'w', encoding='utf-8', newline='\n').write(''.join(out).rstrip() + '\n')

    # remove any subset we no longer keep
    removed = 0
    for f in os.listdir(FONTS):
        if not f.endswith('.woff2'):
            continue
        if f not in kept:
            os.remove(os.path.join(FONTS, f))
            removed += 1

    print('%d file(s) downloaded, %d already present' % (downloaded, len(kept) - downloaded))
    print('%d unused file(s) removed' % removed)
    print('%.0f KB of fonts in fonts/' % (total / 1024))
    print('wrote %s' % os.path.relpath(OUT, ROOT).replace('\\', '/'))


if __name__ == '__main__':
    main()
